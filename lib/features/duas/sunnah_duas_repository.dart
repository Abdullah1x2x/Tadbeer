/// نموذج يمثل دعاءً نبوياً أو جامعاً.
class GeneralDuaItem {
  final String id;
  final String title;
  final String text;
  final String occasion;
  final String source;
  final bool isSunnah;

  const GeneralDuaItem({
    required this.id,
    required this.title,
    required this.text,
    required this.occasion,
    required this.source,
    this.isSunnah = true,
  });
}

