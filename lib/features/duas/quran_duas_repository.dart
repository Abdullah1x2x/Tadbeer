  /// يعيد القائمة الكاملة المعتمدة لأدعية القرآن الكريم مرتبة حسب ترتيب المصحف.
  ///
  /// Returns the complete verified list of Quranic Duas sorted strictly by Quran order.
  List<QuranDua> getDuas({QuranRepository? quranRepository}) {
    if (_cachedDuas != null) return _cachedDuas!;

    final repo = quranRepository ?? QuranRepository.instance;
    final list = <QuranDua>[];

    for (final entry in _catalog) {
      int page = entry.defaultPage;
      if (repo.isLoaded) {
        final ayah = repo.getAyah(entry.surahNumber, entry.ayahNumber);
        if (ayah != null) {
          page = ayah.page;
        }
      }

      list.add(
        QuranDua(
          id: entry.id,
          surahNumber: entry.surahNumber,
          surahName: entry.surahName,
          ayahNumber: entry.ayahNumber,
          ayahEndNumber: entry.ayahEndNumber,
          ayahDisplay: entry.ayahDisplay,
          ayahKey: '${entry.surahNumber}:${entry.ayahDisplay}',
          title: entry.title,
          duaText: entry.duaText,
          page: page,
          rawText: ArabicSearchNormalizer.normalize(entry.duaText),
          category: entry.category,
          alert: null,
          isDirectDua: entry.isDirectDua,
          orderInSurah: entry.orderInSurah,
          verses: entry.verses,
        ),
      );
    }

    _cachedDuas = List.unmodifiable(list);
    return _cachedDuas!;
  }

  /// يبحث فورياً بدون إنترنت في الأدعية القرآنية حسب النص أو العنوان أو السورة أو التصنيف أو رقم الآية.
  ///
  /// Instant offline search across Quranic duas by text, title, surah name, category or ayah number.
  List<QuranDua> search(
    String query, {
    String? categoryFilter,
    QuranRepository? quranRepository,
  }) {
    final all = getDuas(quranRepository: quranRepository);
    final trimmed = query.trim();
    final normQuery = trimmed.isEmpty
        ? ''
        : ArabicSearchNormalizer.normalize(trimmed);
    final isAllCategory =
        categoryFilter == null ||
        categoryFilter.isEmpty ||
        categoryFilter == 'الكل';
    final ayahNumQuery = int.tryParse(trimmed);

    return all.where((dua) {
      // 1. Category Filter Check
      if (!isAllCategory && dua.category != categoryFilter) {
        return false;
      }

      if (normQuery.isEmpty) return true;

      // 2. Search in normalized dua text
      if (dua.rawText.contains(normQuery)) return true;

      // 3. Search in normalized title
      if (ArabicSearchNormalizer.normalize(dua.title).contains(normQuery)) {
        return true;
      }

      // 4. Search in normalized surah name
      if (ArabicSearchNormalizer.normalize(dua.surahName).contains(normQuery)) {
        return true;
      }

      // 5. Search in normalized category name
      if (ArabicSearchNormalizer.normalize(dua.category).contains(normQuery)) {
        return true;
      }

      // 6. Search by ayah number or ayah range string
      if (ayahNumQuery != null &&
          (dua.ayahNumber <= ayahNumQuery &&
                  ayahNumQuery <= dua.ayahEndNumber ||
              dua.verses.any((v) => v.ayahNumber == ayahNumQuery))) {
        return true;
      }
      if (dua.ayahDisplay.contains(trimmed) ||
          dua.verses.any(
            (v) =>
                ArabicSearchNormalizer.toArabicDigits(v.ayahNumber)
                    .contains(trimmed) ||
                '${v.ayahNumber}'.contains(trimmed),
          )) {
        return true;
      }

      return false;
    }).toList();
  }

